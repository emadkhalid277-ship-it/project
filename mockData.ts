export const generateHistory = (students: Student[]): DailyRecord[] => {
  const records: DailyRecord[] = [];
  const today = new Date().toISOString().split('T')[0];
  students.forEach(s => {
    records.push({
      id: `rec-${s.id}-${today}`,
      studentId: s.id,
      date: today,
      attendance: 'حاضر',
      recitation: 'لم يسمّع',
      evaluation: 'جيد',
      notes: ''
    });
  });
  return records;
};
