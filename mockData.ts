export const generateHistory = (students: Student[]): DailyRecord[] => {
  const records: DailyRecord[] = [];
  const dates = Array.from({ length: 7 }, (_, i) => {
    const d = new Date();
    d.setDate(d.getDate() - i);
    return d.toISOString().split('T')[0];
  });

  students.forEach(s => {
    dates.forEach(date => {
      const random = Math.random();
      records.push({
        id: `rec-${s.id}-${date}`,
        studentId: s.id,
        date,
        attendance: random > 0.1 ? (random > 0.8 ? 'متأخر' : 'حاضر') : 'غائب',
        recitation: random > 0.3 ? 'سمّع' : 'لم يسمّع',
        evaluation: random > 0.7 ? 'ممتاز' : (random > 0.4 ? 'جيد جدًا' : 'جيد'),
        notes: random > 0.9 ? 'يحتاج مراجعة المتشابهات' : ''
      });
    });
  });

  return records;
};
